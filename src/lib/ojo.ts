/** Radio de la pupila (hueco negro en el centro). */
export const EYE_PUPIL_R = 0.1452;

type Point = (x: number, y: number) => [number, number];

/** Recorre el contorno con `map` aplicado a cada punto (escala, centro, ejes). */
export function traceEyeOutline(
  map: Point,
  moveTo: (x: number, y: number) => void,
  curveTo: (c1x: number, c1y: number, c2x: number, c2y: number, x: number, y: number) => void,
) {
  moveTo(...map(START[0], START[1]));
  for (let i = 0; i < CURVES.length; i += 6) {
    curveTo(
      ...map(CURVES[i], CURVES[i + 1]),
      ...map(CURVES[i + 2], CURVES[i + 3]),
      ...map(CURVES[i + 4], CURVES[i + 5]),
    );
  }
}

/** `d` de SVG del contorno (sin la pupila), escalado por `s` y centrado en (cx, cy). */
export function eyeOutlinePath(s: number, cx: number, cy: number) {
  const f = (n: number) => n.toFixed(2);
  let d = "";
  traceEyeOutline(
    (x, y) => [cx + x * s, cy + y * s],
    (x, y) => {
      d += `M ${f(x)} ${f(y)}`;
    },
    (a, b, c, e, x, y) => {
      d += ` C ${f(a)} ${f(b)} ${f(c)} ${f(e)} ${f(x)} ${f(y)}`;
    },
  );
  return `${d} Z`;
}
